interface I18nState {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string) => string;
}

export const useI18n = create<I18nState>()(
  persist(
    (set, get) => ({
      language: 'el',
      setLanguage: (lang) => set({ language: lang }),
      t: (key: string) => {
        const { language } = get();
        return translations[language]?.[key] ?? translations['en']?.[key] ?? key;
      },
    }),
    {
      name: 'orange-language',
    }
  )
);
